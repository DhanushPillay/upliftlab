"""Monte Carlo calibration of the Phase 1 readout estimator."""

from __future__ import annotations

import math
import platform
import sys
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Any

import numpy as np

from upliftlab.experiment.estimators import difference_in_means
from upliftlab.simulation.scenarios import SCENARIOS, Scenario, draw_experiment


@dataclass(frozen=True, slots=True)
class ScenarioResult:
    name: str
    description: str
    replications: int
    n: int
    true_ate: float
    mean_estimate: float
    empirical_se: float
    mean_standard_error: float
    bias: float
    coverage: float
    coverage_mcse: float
    rejection_rate: float
    rejection_mcse: float

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "description": self.description,
            "replications": self.replications,
            "n": self.n,
            "true_ate": self.true_ate,
            "mean_estimate": self.mean_estimate,
            "empirical_se": self.empirical_se,
            "mean_standard_error": self.mean_standard_error,
            "bias": self.bias,
            "coverage": self.coverage,
            "coverage_mcse": self.coverage_mcse,
            "rejection_rate": self.rejection_rate,
            "rejection_mcse": self.rejection_mcse,
        }


@dataclass(frozen=True, slots=True)
class SimulationReport:
    schema_version: int
    seed: int
    alpha: float
    scenarios: tuple[ScenarioResult, ...]
    created_at: str
    python_version: str
    numpy_version: str
    platform_name: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "seed": self.seed,
            "alpha": self.alpha,
            "created_at": self.created_at,
            "python_version": self.python_version,
            "numpy_version": self.numpy_version,
            "platform": self.platform_name,
            "scenarios": [scenario.to_dict() for scenario in self.scenarios],
        }


def _binomial_mcse(probability: float, replications: int) -> float:
    return math.sqrt(probability * (1.0 - probability) / replications)


def run_scenario(
    scenario: Scenario,
    *,
    replications: int,
    seed: int,
    alpha: float = 0.05,
) -> ScenarioResult:
    if replications < 100:
        raise ValueError("replications must be at least 100")
    rng = np.random.default_rng(seed)
    estimates = np.empty(replications, dtype=float)
    standard_errors = np.empty(replications, dtype=float)
    covered = np.empty(replications, dtype=bool)
    rejected = np.empty(replications, dtype=bool)

    for index in range(replications):
        outcome, treatment = draw_experiment(scenario, rng)
        result = difference_in_means(outcome, treatment, alpha=alpha)
        estimates[index] = result.estimate
        standard_errors[index] = result.standard_error
        covered[index] = result.ci_low <= scenario.true_ate <= result.ci_high
        rejected[index] = result.p_value < alpha

    coverage = float(covered.mean())
    rejection_rate = float(rejected.mean())
    return ScenarioResult(
        name=scenario.name,
        description=scenario.description,
        replications=replications,
        n=scenario.n,
        true_ate=scenario.true_ate,
        mean_estimate=float(estimates.mean()),
        empirical_se=float(estimates.std(ddof=1)),
        mean_standard_error=float(standard_errors.mean()),
        bias=float(estimates.mean() - scenario.true_ate),
        coverage=coverage,
        coverage_mcse=_binomial_mcse(coverage, replications),
        rejection_rate=rejection_rate,
        rejection_mcse=_binomial_mcse(rejection_rate, replications),
    )


def run_simulation(
    *,
    replications: int = 5000,
    seed: int = 42,
    alpha: float = 0.05,
    scenarios: tuple[Scenario, ...] = SCENARIOS,
) -> SimulationReport:
    if seed < 0:
        raise ValueError("seed must be non-negative")
    if not 0.0 < alpha < 1.0:
        raise ValueError("alpha must be strictly between 0 and 1")
    results = tuple(
        run_scenario(scenario, replications=replications, seed=seed + offset, alpha=alpha)
        for offset, scenario in enumerate(scenarios)
    )
    return SimulationReport(
        schema_version=1,
        seed=seed,
        alpha=alpha,
        scenarios=results,
        created_at=datetime.now(UTC).isoformat(timespec="seconds"),
        python_version=sys.version.split()[0],
        numpy_version=np.__version__,
        platform_name=platform.platform(),
    )


def render_simulation(report: SimulationReport) -> str:
    alpha_label = f"{100 * (1 - report.alpha):g}%"
    lines = [
        "# Simulation benchmark",
        "",
        "Generated by `upliftlab simulate`. Every rate has a Monte Carlo standard error.",
        "",
        f"- Seed: {report.seed}",
        f"- Replications per scenario: {report.scenarios[0].replications:,}",
        f"- Confidence level: {alpha_label}",
        f"- Created: {report.created_at}",
        f"- Environment: Python {report.python_version}, NumPy {report.numpy_version}, "
        f"{report.platform_name}",
        "",
        "| Scenario | True ATE | Mean estimate | Bias | Empirical SE | Mean SE | "
        f"Coverage ({alpha_label}) | Rejection at {report.alpha} |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    lines.extend(
        f"| {result.name} | {result.true_ate:.4f} | {result.mean_estimate:.4f} | "
        f"{result.bias:+.4f} | {result.empirical_se:.4f} | "
        f"{result.mean_standard_error:.4f} | "
        f"{result.coverage:.3f} +/- {result.coverage_mcse:.3f} | "
        f"{result.rejection_rate:.3f} +/- {result.rejection_mcse:.3f} |"
        for result in report.scenarios
    )
    lines.extend(
        [
            "",
            "## Reading this table",
            "",
            "- Coverage should be near the nominal level; the +/- value is one MCSE.",
            "- Rejection at alpha is the Type I error rate under the null and power elsewhere.",
            "- Empirical SE and mean SE should agree; a large gap indicates a variance bug.",
            "- Bias is the mean estimate minus the known truth.",
            "",
            "Uplift ranking, Qini/AUUC, policy value, and budget regret are Phase 2/3 "
            "benchmarks and are not measured here.",
            "",
        ]
    )
    return "\n".join(lines)
