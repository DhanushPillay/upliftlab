"""Markdown rendering for experiment readouts."""

from __future__ import annotations

import math

from upliftlab.results import ATEResult, ReadoutResult


def _number(value: float | None, digits: int = 4) -> str:
    if value is None or math.isnan(value):
        return "n/a"
    if math.isinf(value):
        return "inf" if value > 0 else "-inf"
    return f"{value:.{digits}f}"


def _p_value(value: float | None) -> str:
    if value is None or math.isnan(value):
        return "n/a"
    if value < 0.0001:
        return "<0.0001"
    return f"{value:.4f}"


def _percent(value: float) -> str:
    if math.isnan(value):
        return "n/a"
    if math.isinf(value):
        return "inf" if value > 0 else "-inf"
    return f"{value * 100:.1f}%"


def _estimate_row(label: str, result: ATEResult) -> str:
    return (
        f"| {label} | {_number(result.estimate)} | "
        f"[{_number(result.ci_low)}, {_number(result.ci_high)}] | "
        f"{_p_value(result.p_value)} |"
    )


def render_readout(result: ReadoutResult) -> str:
    """Render a compact, reproducible Markdown report."""
    ci_label = f"{100 * (1 - result.alpha):g}% CI"
    lines: list[str] = [
        f"# Experiment readout: {result.dataset}",
        "",
        "Intent-to-treat analysis. Generated by upliftlab; no numbers are hand-edited.",
        "",
        "## Summary",
        "",
        f"- Rows: {result.rows:,}",
        (f"- Analysed sample: {result.ate.n_treated:,} treated, {result.ate.n_control:,} control"),
        f"- Primary outcome: `{result.outcome}`",
        f"- CUPED covariate: `{result.covariate}`",
        f"- Alpha: {result.alpha}",
        f"- Bootstrap draws: {result.bootstrap:,} (seed {result.seed})",
        "",
        f"| Metric | Estimate | {ci_label} | p-value |",
        "| --- | ---: | ---: | ---: |",
        _estimate_row("ATE (Welch, primary)", result.ate),
        (
            f"| Bootstrap (percentile) | {_number(result.bootstrap_result.estimate)} | "
            f"[{_number(result.bootstrap_result.ci_low)}, "
            f"{_number(result.bootstrap_result.ci_high)}] | n/a |"
        ),
        _estimate_row("CUPED adjusted (sensitivity)", result.cuped.adjusted),
        "",
        f"CUPED theta: {_number(result.cuped.theta)}. "
        f"Variance reduction: {_percent(result.cuped.variance_reduction)}. "
        f"Outcome-covariate correlation: {_number(result.cuped.correlation)}.",
        "",
        "## Sample ratio",
        "",
        "| Arm | Observed | Expected |",
        "| --- | ---: | ---: |",
    ]

    for label, observed, expected in zip(
        result.srm.labels,
        result.srm.counts,
        result.srm.expected_counts,
        strict=True,
    ):
        lines.append(f"| {label} | {observed:,} | {expected:,.1f} |")

    status = "FAIL" if result.srm.detected else "pass"
    lines.extend(
        [
            "",
            f"SRM check ({result.srm.method}): p = {_p_value(result.srm.p_value)}; "
            f"threshold = {result.srm.alpha}; status = **{status}**.",
            "",
            "## Covariate balance",
            "",
            "Sorted by absolute standardized mean difference (SMD). "
            "Categorical covariates appear as dummy proportions.",
            "",
            "| Covariate | Treated mean | Control mean | SMD |",
            "| --- | ---: | ---: | ---: |",
        ]
    )

    for row in result.balance[:12]:
        flag = " (imbalanced)" if row.smd is not None and abs(row.smd) > 0.1 else ""
        lines.append(
            f"| `{row.covariate}` | {_number(row.treated_mean, 3)} | "
            f"{_number(row.control_mean, 3)} | {_number(row.smd, 3)}{flag} |"
        )
    if len(result.balance) > 12:
        lines.append(f"| ... | | | ({len(result.balance) - 12} more rows) |")

    lines.extend(
        [
            "",
            "## Caveats",
            "",
        ]
    )
    lines.extend(f"- {caveat}" for caveat in result.caveats)
    lines.extend(
        [
            "",
            "## Not in this report",
            "",
            "Per-customer uplift, budget-constrained targeting, and the Criteo case study "
            "are later phases. This file answers one question: did the email change the "
            f"`{result.outcome}` rate, and how precise is that answer?",
            "",
        ]
    )
    return "\n".join(lines)
